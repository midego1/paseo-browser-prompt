// Copies the Server browser files (server-browser/) into server/server-browser-files.ts. The daemon
// bundles the plugin's server code, so the files travel inside it and the plugin can build the image
// and write its launcher without knowing its install directory. Run after changing server-browser/:
//   node scripts/embed-server-browser.mjs
// A test fails when the embedded copy and server-browser/ differ.
import { readFileSync, writeFileSync } from "node:fs";

/** The image's build context; its hash is part of the image tag. */
export const SERVER_BROWSER_FILE_NAMES = ["Dockerfile", "entrypoint.mjs", "mcp-filter.mjs", "package-lock.json", "package.json", "proxy-main.mjs", "proxy.mjs"];
/** Files the plugin writes to its state directory and uses on the host: the launcher and the seccomp profile. */
export const SERVER_BROWSER_RUNTIME_FILE_NAMES = ["launch.mjs", "seccomp.json"];

const readDefault = (name) => readFileSync(new URL(`../server-browser/${name}`, import.meta.url), "utf8");

export function renderEmbedded(read = readDefault) {
  const map = (names) => names.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(read(name))},`);
  return [
    "// Generated by scripts/embed-server-browser.mjs from server-browser/. Do not edit by hand.",
    "/** The Server browser image's build context, file name to content. */",
    "export const SERVER_BROWSER_FILES: Readonly<Record<string, string>> = {",
    ...map(SERVER_BROWSER_FILE_NAMES),
    "};",
    "",
    "/** Host-side files: the session launcher and the browser container's seccomp profile. */",
    "export const SERVER_BROWSER_RUNTIME_FILES: Readonly<Record<string, string>> = {",
    ...map(SERVER_BROWSER_RUNTIME_FILE_NAMES),
    "};",
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL("../server/server-browser-files.ts", import.meta.url), renderEmbedded());
  console.log("server/server-browser-files.ts updated");
}
