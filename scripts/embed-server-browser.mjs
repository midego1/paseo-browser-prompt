// Copies the Server browser files (server-browser/, the signed-in image context signed-in/ and its Bitwarden variant signed-in-bitwarden/) into server/server-browser-files.ts. The daemon
// bundles the plugin's server code, so the files travel inside it and the plugin can build the image
// and write its launcher without knowing its install directory. Run after changing server-browser/:
//   node scripts/embed-server-browser.mjs
// A test fails when the embedded copy and server-browser/ differ.
import { readFileSync, writeFileSync } from "node:fs";

/** The image's build context; its hash is part of the image tag. */
export const SERVER_BROWSER_FILE_NAMES = [
  "Dockerfile",
  "bitwarden-lock.mjs",
  "cdp-filter.mjs",
  "entrypoint.mjs",
  "mcp-filter.mjs",
  "package-lock.json",
  "package.json",
  "proxy-main.mjs",
  "proxy.mjs",
  "relay-main.mjs",
  "relay.mjs",
];
/** Files the plugin writes to its state directory and uses on the host: the launcher and the seccomp profile. */
export const SERVER_BROWSER_RUNTIME_FILE_NAMES = ["launch.mjs", "seccomp.json"];

/** The signed-in Server browser image's build context (signed-in/): neko plus the plugin's overrides. */
export const SIGNED_IN_FILE_NAMES = ["Dockerfile", "chromium-start.sh", "chromium.conf", "policies.json", "viewer.css", "viewer.js"];
/** The Bitwarden variant's build context (signed-in-bitwarden/): built on the signed-in image only after the owner's consent. */
export const SIGNED_IN_BITWARDEN_FILE_NAMES = ["Dockerfile", "bitwarden.json", "install-bitwarden.py", "policy-overlay.json"];

const readDefault = (name) => readFileSync(new URL(`../server-browser/${name}`, import.meta.url), "utf8");
const readSignedInDefault = (name) => readFileSync(new URL(`../signed-in/${name}`, import.meta.url), "utf8");
const readBitwardenDefault = (name) => readFileSync(new URL(`../signed-in-bitwarden/${name}`, import.meta.url), "utf8");

export function renderEmbedded(read = readDefault, readSignedIn = readSignedInDefault, readBitwarden = readBitwardenDefault) {
  const map = (names, reader = read) => names.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(reader(name))},`);
  return [
    "// Generated by scripts/embed-server-browser.mjs from server-browser/. Do not edit by hand.",
    "/** The Server browser image's build context, file name to content. */",
    "export const SERVER_BROWSER_FILES: Readonly<Record<string, string>> = {",
    ...map(SERVER_BROWSER_FILE_NAMES),
    "};",
    "",
    "/** Host-side files: the session launcher and the browser container's seccomp profile. */",
    "export const SERVER_BROWSER_RUNTIME_FILES: Readonly<Record<string, string>> = {",
    ...map(SERVER_BROWSER_RUNTIME_FILE_NAMES),
    "};",
    "",
    "/** The signed-in Server browser image's build context (signed-in/), file name to content. */",
    "export const SIGNED_IN_FILES: Readonly<Record<string, string>> = {",
    ...map(SIGNED_IN_FILE_NAMES, readSignedIn),
    "};",
    "",
    "/** The Bitwarden variant's build context (signed-in-bitwarden/), file name to content. */",
    "export const SIGNED_IN_BITWARDEN_FILES: Readonly<Record<string, string>> = {",
    ...map(SIGNED_IN_BITWARDEN_FILE_NAMES, readBitwarden),
    "};",
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL("../server/server-browser-files.ts", import.meta.url), renderEmbedded());
  console.log("server/server-browser-files.ts updated");
}
