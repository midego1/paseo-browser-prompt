// Copies the Server browser build context (server-browser/) into server/server-browser-files.ts.
// The daemon bundles the plugin's server code, so the files travel inside it and the plugin can
// build the image without knowing its install directory. Run after changing server-browser/:
//   node scripts/embed-server-browser.mjs
// A test fails when the embedded copy and server-browser/ differ.
import { readFileSync, writeFileSync } from "node:fs";

export const SERVER_BROWSER_FILE_NAMES = ["Dockerfile", "entrypoint.mjs", "package-lock.json", "package.json", "proxy.mjs"];

export function renderEmbedded(read = (name) => readFileSync(new URL(`../server-browser/${name}`, import.meta.url), "utf8")) {
  const entries = SERVER_BROWSER_FILE_NAMES.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(read(name))},`);
  return [
    "// Generated by scripts/embed-server-browser.mjs from server-browser/. Do not edit by hand.",
    "/** The Server browser image's build context, file name to content. */",
    "export const SERVER_BROWSER_FILES: Readonly<Record<string, string>> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL("../server/server-browser-files.ts", import.meta.url), renderEmbedded());
  console.log("server/server-browser-files.ts updated");
}
